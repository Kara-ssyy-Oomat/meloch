// ===================================================================
// КЕРБЕН — «Штук в коробке» (unitsPerBox).
// 0 — продажа по коробкам для товара ВЫКЛЮЧЕНА: сколько бы штук клиент
// ни заказал, коробки не считаются, пока админ не впишет число.
// Если поле у товара вообще не заполнено — берём BOX_UNITS_DEFAULT.
// ===================================================================

var BOX_UNITS_DEFAULT = 1000;

// Первое явно заданное значение из переданных (0 — это тоже ответ,
// поэтому обычное `a || b || 72` здесь не годится: оно теряет ноль).
function getBoxUnits() {
  for (var i = 0; i < arguments.length; i++) {
    var n = parseInt(arguments[i], 10);
    if (!isNaN(n) && n >= 0) return n;
  }
  return BOX_UNITS_DEFAULT;
}
